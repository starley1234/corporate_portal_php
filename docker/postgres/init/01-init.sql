-- Векторное хранилище эмбеддингов (семантический поиск, RAG)
CREATE EXTENSION IF NOT EXISTS vector;

-- Триграммы: быстрый поиск по подстроке, нечёткий поиск
CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- Снятие акцентов/регистра для полнотекстового поиска
CREATE EXTENSION IF NOT EXISTS unaccent;

-- UUID (если понадобится внешняя идентификация записей между сервисами)
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
