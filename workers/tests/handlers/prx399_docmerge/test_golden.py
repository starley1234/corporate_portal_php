"""Золотой корпус prx399: анонимизированные образцы «договор + ДС».

Смысл — страховка детерминированного контура: любые правки regex/статистики
ast_text не должны изменить распознавание типовых формулировок. Ожидаемые
якоря зафиксированы; корпус расширяется по мере реальных пакетов (вышедшие
из под рук кейсы — сюда). Сборку (Merge::build) золотит PHP-контракт
tests/Contracts/prx399_merge_build.php.
"""
from prx_workers.handlers.prx399_docmerge import ast_text

BASE = """ДОГОВОР ПОСТАВКИ № 41
г. Липки, 12.01.2026

ООО «Лютик» (Поставщик) и ООО «Клевер» (Покупатель) заключили договор
о поставке канцелярских товаров.

Раздел 1. Предмет договора
1.1. Поставщик обязуется поставить товар в срок до 30.06.2026.
1.2. Ассортимент и цены согласованы в Приложении 1.

Раздел 2. Порядок расчётов и ответственность
2.1. Цена договора — 480 000 руб., НДС включён.
2.1.1. Оплата — в течение 10 рабочих дней с момента выставления счёта.
2.2. За просрочку поставки — неустойка 0,1% в день.

Статья 5. Форс-мажор по применимому праву.
"""

DS = """ДОПОЛНИТЕЛЬНОЕ СОГЛАШЕНИЕ № 1
к Договору поставки № 41 от 12.01.2026

1. Пункт 2.1 изложить в следующей редакции: «Цена договора — 512 000 руб., НДС включён».
2. Дополнить пунктом 2.3: «Отсрочка платежа — 21 календарный день».
3. Пункт 2.2 исключить.
"""

EXPECTED_BASE_PATHS = ["0", "раздел-1", "1.1", "1.2", "раздел-2", "2.1", "2.1.1", "2.2", "ст-5"]


def test_golden_base_anchors_are_stable():
    nodes = ast_text.parse(BASE)
    assert [node["path"] for node in nodes] == EXPECTED_BASE_PATHS
    node_211 = next(node for node in nodes if node["path"] == "2.1.1")
    assert "10 рабочих дней" in node_211["text"]


def test_golden_render_roundtrip_keeps_key_facts():
    rendered = ast_text.render(ast_text.parse(BASE))
    for phrase in ("480 000", "Форс-мажор", "0,1% в день", "Приложении 1"):
        assert phrase in rendered


def test_golden_references_of_base():
    # ссылки, на которые опираются ДС типового пакета
    assert ast_text.references(DS) == ["2.1", "2.3", "2.2"]


def test_golden_stats_are_clean():
    report = ast_text.stats(BASE, ast_text.parse(BASE))
    assert report["unrecognized"] == [] and report["duplicates"] == []
