 * позволяет проверять и человека (сессия + ACL, Prx_Actor), и машинный ключ
 * prx150 (Prx150_Principal) одним и тем же правилом.
 *
 * Роли и can() у машинного principal нет намеренно: RBAC сотрудника и scope
 * ключа — разные границы, смешивать их нельзя.
 */
interface Prx_Principal
{
    /** Организация контекста или NULL, если её нет. */
    public function organizationId(): ?int;
}
