<?php defined('SYSPATH') or die('No direct script access.');

/**
 * Конфиг NJ-677 «Разговор с ИИ голосом» (nj677_talk).
 *
 * Что здесь: пороги разговора и лимиты. Чего здесь НЕТ и быть не должно:
 * адреса и ключа OmniVoice — их держит nj665_voice (NJ665_API_URL/KEY), потому
 * что клиент внешнего API в проекте один. Модель LLM берётся из фасада Llm.
 *
 * Переменные окружения — полные слаги модуля (правило владельца 21.09):
 * NJ677_MODEL, NJ677_VOICE, NJ677_LANGUAGE и т.д. Новые ключи дописывать
 * в хвост .env.example.
 *
 * Значения по умолчанию выбраны под голосовой разговор, а не под «озвучку
 * статьи»: ответ короткий (иначе ждать его дольше, чем разговаривать),
 * контекст — последние реплики, части озвучки маленькие, чтобы первая фраза
 * зазвучала сразу.
 */
return [

    // «провайдер::модель» для фасада Llm. Пусто — модель платформы
    // (config/llm.php → default_model). Для разговора полезна быстрая модель:
    // задержка ответа целиком состоит из её времени.
    'model'     => (string) getenv('NJ677_MODEL'),

    // Голос OmniVoice. Пусто — голос по умолчанию из nj665.
    'voice'     => (string) getenv('NJ677_VOICE'),

    // Язык распознавания и синтеза (пусто — модель определяет сама).
    'language'  => ((string) getenv('NJ677_LANGUAGE') !== '' ? (string) getenv('NJ677_LANGUAGE') : 'ru'),

    // Скорость речи. В разговоре чуть быстрее книжной: 1.0–1.15 читается
    // естественно, выше — уже «диктор спешит».
    'speed'     => (float) (getenv('NJ677_SPEED') ?: 1.05),

    // Формат озвучки. mp3 — компактный, но у некоторых движков он режется по
    // высоким частотам и звучит «приглушённо»; wav — без потерь, файлы больше.
    'tts_format' => strtolower((string) getenv('NJ677_TTS_FORMAT')) ?: 'mp3',

    'limits' => [
        // Реплика пользователя: длиннее — это уже не разговор, а монолог.
        'turn_chars'    => (int) (getenv('NJ677_TURN_CHARS') ?: 2000),

        // Сколько знаков ответа озвучиваем (остальное видно текстом).
        'speak_chars'   => (int) (getenv('NJ677_SPEAK_CHARS') ?: 1600),

        // Часть озвучки: маленькая часть — быстрый первый звук.
        'tts_chars'     => (int) (getenv('NJ677_TTS_CHARS') ?: 200),
        'tts_parts'     => (int) (getenv('NJ677_TTS_PARTS') ?: 10),

        // Контекст разговора: последние реплики и общий бюджет знаков.
        'history_turns' => (int) (getenv('NJ677_HISTORY_TURNS') ?: 12),
        'history_chars' => (int) (getenv('NJ677_HISTORY_CHARS') ?: 6000),

        // Ответ модели: 1–3 предложения. Больше — и разговор превращается
        // в ожидание, поэтому это лимит не «для экономии», а по делу.
        'max_tokens'    => (int) (getenv('NJ677_MAX_TOKENS') ?: 220),
        'temperature'   => (float) (getenv('NJ677_TEMPERATURE') ?: 0.6),

        // Запись с микрофона: размер файла и длительность одной реплики.
        'audio_kb'      => (int) (getenv('NJ677_AUDIO_MAX_KB') ?: 4096),
        'audio_sec'     => (int) (getenv('NJ677_AUDIO_MAX_SEC') ?: 60),
    ],

    // Лимитер по аккаунту: один ход = распознавание + модель + синтез, все три
    // занимают чужое железо. Считается по репликам пользователя в БД.
    'rate' => [
        'per_minute' => (int) (getenv('NJ677_RATE_PER_MINUTE') ?: 20),
        'per_hour'   => (int) (getenv('NJ677_RATE_PER_HOUR') ?: 240),
    ],

    // Что модель получает как системную роль. Правила простые и жёсткие:
    // ответ читают вслух, поэтому списки, markdown и «конечно, с удовольствием»
    // только мешают.
    'prompt' => [
        'system' => ((string) getenv('NJ677_SYSTEM_PROMPT') !== ''
            ? (string) getenv('NJ677_SYSTEM_PROMPT')
            : 'Ты — голосовой собеседник сервиса N2J. Твой ответ прочитают вслух, '
                .'поэтому говори простыми законченными фразами: одно-три предложения, '
                .'без списков, заголовков, markdown, ссылок и смайлов. Не повторяй '
                .'вопрос и не начинай с «конечно» и «разумеется» — сразу по делу. '
                .'Если для точного ответа не хватает данных, задай один короткий '
                .'уточняющий вопрос. Отвечай на языке собеседника.'),
    ],

    // Сколько последних разговоров показывать на странице (возврат к теме).
    'recent_limit' => (int) (getenv('NJ677_RECENT_LIMIT') ?: 5),

    // Сколько дней хранить разговоры (объявлено и в манифесте — чистка nj100).
    'ttl_days' => (int) (getenv('NJ677_TTL_DAYS') ?: 30),
];
