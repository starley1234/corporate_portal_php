/**
 * Инициализация модуля nj677_talk («Разговор с ИИ голосом»).
 *
 *   GET  /talk              страница разговора (микрофон, история, выбор голоса);
 *   POST /talk/api/hear     запись с микрофона → текст (распознавание);
 *   POST /talk/api/reply     текст → ответ модели + части для озвучки;
 *   POST /talk/api/say       часть ответа → аудио (сырые байты).
 *
 * Почему три точки, а не одна «на весь ход»: разговор держится на скорости
 * отдельных шагов. Пока модель думает, человек уже видит свои слова (hear),
 * а пока играет первая фраза ответа, остальные синтезируются (say по частям).
 * Один запрос на весь ход дал бы одну длинную паузу вместо трёх коротких.
 *
 * Маршруты API объявлены ДО страницы: сегмент `<action>` в Kohana не должен
 * перехватить `/talk/api/...` (урок §24.5 — имя действия задаёт маршрут).
 */

Route::set('nj677_api_hear', 'talk/api/hear')
    ->defaults(['controller' => 'Nj677_Api', 'action' => 'hear']);

Route::set('nj677_api_reply', 'talk/api/reply')
    ->defaults(['controller' => 'Nj677_Api', 'action' => 'reply']);

Route::set('nj677_api_say', 'talk/api/say')
    ->defaults(['controller' => 'Nj677_Api', 'action' => 'say']);

Route::set('nj677_page', 'talk')
    ->defaults(['controller' => 'Nj677_Talk', 'action' => 'index']);

