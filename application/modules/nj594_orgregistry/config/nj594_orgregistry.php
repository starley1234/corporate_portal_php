<?php defined('SYSPATH') or die('No direct script access.');

/**
 * Конфиг «Справочника организаций» (nj594_orgregistry).
 *
 * Пороги запросов к ФНС (egrul.nalog.ru): реестр не любит частых обращений, а
 * сервис отвечает отказами при перегрузке. Лимит мягкий: он не блокирует
 * пользователя, а просит подождать минуту и подсказывает, когда вернуться.
 *
 * Значения переопределяются env (секретов здесь нет — только пороги).
 */
/**
 * Значение из env: пусто/не задано — берём умолчание. Именно так, а не через
 * `?:`: «0» — это осмысленное значение (например, cooldown=0 выключает паузу),
 * а короткое `getenv(...) ?: 5` вернуло бы умолчание вместо нуля.
 */
$env_int = function ($key, $default) {
    $v = getenv($key);

    return ($v === FALSE OR trim((string) $v) === '') ? (int) $default : (int) $v;
};

return [
    'fns' => [
        // сколько запросов к ФНС разрешено с одного IP в минуту / час
        'per_minute'     => $env_int('NJ594_FNS_PER_MINUTE', 5),
        'per_hour'       => $env_int('NJ594_FNS_PER_HOUR', 30),

        // общий кап платформы за час (все IP вместе) — защита от «толпы»
        'total_per_hour' => $env_int('NJ594_FNS_TOTAL_PER_HOUR', 120),

        // если по этому же номеру/названию ФНС только что ничего не нашла,
        // повторно не спрашиваем столько секунд (0 — выключить паузу)
        'cooldown_sec'   => $env_int('NJ594_FNS_COOLDOWN', 120),

        // таймаут одного HTTP-запроса к egrul.nalog.ru, секунд
        'timeout'        => $env_int('NJ594_FNS_TIMEOUT', 12),
    ],
];
