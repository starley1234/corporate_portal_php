<?php defined('SYSPATH') or die('No direct script access.');

/**
 * Настройки семантического поиска (модуль prx115_semantic).
 *
 * Здесь два блока:
 *   * 'sources' — реестр источников индексации: откуда берутся тексты, что
 *     должны лежать векторами. По нему панель /prx115 считает ПОКРЫТИЕ, догоняет
 *     отставшие тексты («Догнать») и убирает мусор (векторы удалённых записей);
 *   * 'search'  — как ведёт себя поиск: порог расстояния и гибрид с текстовым
 *     поиском, плюс кэш эмбеддингов запросов.
 */
return [

    /**
     * Источники индексации.
     *
     * Каждый источник — SQL, который отдаёт ТРИ колонки:
     *   id       — идентификатор записи (станет entity_id вектора, приводим к тексту);
     *   content  — ТОЧНО тот же текст, что уходил в Service_Prx115_Semantic::index_texts()
     *              (иначе хеш не совпадёт и покрытие будет вечно «неполным»);
     *   metadata — jsonb с метаданными вектора (необязательно).
     *
     * ВАЖНО: источник обязан перечислять ВСЕ записи коллекции (без фильтров по
     * дате и без LIMIT) — по нему считается покрытие и удаляется мусор.
     *
     * Как добавить свой модуль: скопируйте блок, поменяйте collection/entity на
     * те, что передаёт модуль в index_texts(), и напишите SQL по своей таблице.
     * Ничего в коде править не нужно — панель, «Догнать» и «Убрать мусор»
     * подхватят источник сами.
     */
    // Технический RAG-кэш доступен только администраторам.
    // Корпоративные документы должны иметь отдельные ACL-aware коллекции.
    'sources' => [
        'prx560_knowledge' => [
            'title' => 'Техническая база знаний',
            'collection' => 'prx560_knowledge',
            'entity' => 'doc',
            'sql' => "SELECT d.id, d.title || E'\\n' || d.content AS content,
                      jsonb_build_object('source', d.source_module, 'kind', d.kind) AS metadata
                      FROM prx_560_docs d",
        ],
    ],

    'search' => [
        'max_distance' => 0.6,
        'hybrid'       => TRUE,
        'fulltext_min_length' => 3,   // короче — по тексту не ищем (слишком много шума)
    ],

    /**
     * Кэш эмбеддингов поисковых запросов (таблица prx_115_query_cache).
     *
     * Один и тот же запрос («вакансии аналитик», «резюме Python») не должен
     * каждый раз стоить вызова эмбеддинг-сервера. Кэш живёт в базе, поэтому
     * работает для всех процессов сайта и переживает перезапуск.
     */
    'cache' => [
        'enabled'   => TRUE,
        'ttl_days'  => 30,   // старше — удаляем
        'max_rows'  => 500,  // больше — чистим самые давно неиспользованные
    ],

    /**
     * Журнал поисковых запросов (таблица prx_115_searches).
     *
     * Панель /prx115 отвечает на вопрос «поиск реально находит?» — для этого
     * храним последние запросы: что искали, сколько нашлось (и чем — смыслом
     * или словами), сколько занял вызов и была ли ошибка.
     *
     * keep — сколько последних записей держим; 0 — журнал выключен.
     */
    'searches' => [
        'keep' => 200,
    ],
];
