<?php defined('SYSPATH') or die('No direct script access.');

/**
 * Настройки семантического поиска (модуль nj115_semantic).
 *
 * Здесь два блока:
 *   * 'sources' — реестр источников индексации: откуда берутся тексты, что
 *     должны лежать векторами. По нему панель /nj115 считает ПОКРЫТИЕ, догоняет
 *     отставшие тексты («Догнать») и убирает мусор (векторы удалённых записей);
 *   * 'search'  — как ведёт себя поиск: порог расстояния и гибрид с текстовым
 *     поиском, плюс кэш эмбеддингов запросов.
 */
return [

    /**
     * Источники индексации.
     *
     * Каждый источник — SQL, который отдаёт ТРИ колонки:
     *   id       — идентификатор записи (станет entity_id вектора, приводим к тексту);
     *   content  — ТОЧНО тот же текст, что уходил в Service_Nj115_Semantic::index_texts()
     *              (иначе хеш не совпадёт и покрытие будет вечно «неполным»);
     *   metadata — jsonb с метаданными вектора (необязательно).
     *
     * ВАЖНО: источник обязан перечислять ВСЕ записи коллекции (без фильтров по
     * дате и без LIMIT) — по нему считается покрытие и удаляется мусор.
     *
     * Как добавить свой модуль: скопируйте блок, поменяйте collection/entity на
     * те, что передаёт модуль в index_texts(), и напишите SQL по своей таблице.
     * Ничего в коде править не нужно — панель, «Догнать» и «Убрать мусор»
     * подхватят источник сами.
     */
    'sources' => [

        // База знаний платформы (nj560): коллекция nj560_knowledge, сущность 'doc'.
        // Текст собирается так же, как в Service_Nj560_Knowledge::store():
        // «title . "\n" . content» — иначе хеш не совпадёт с записанным вектором.
        'nj560_knowledge' => [
            'title'      => 'База знаний (nj560)',
            'collection' => 'nj560_knowledge',
            'entity'     => 'doc',
            'sql'        => "SELECT d.id,
                                    d.title || E'\\n' || d.content AS content,
                                    jsonb_build_object('source', d.source_module, 'kind', d.kind) AS metadata
                             FROM nj_560_docs d",
        ],

        // Глобальный каталог MCP-серверов (nj676_mcphub): коллекция
        // nj676_mcphub, сущность 'server', id — slug карточки.
        //
        // Формула текста ОБЯЗАНА совпадать с Service_Nj676_Semantic::document():
        // имя, описание, русское имя, русское описание, категории, «имя
        // описание» каждого инструмента. Иначе хеш не сойдётся, и «Догнать»
        // будет пересчитывать вечно неполное покрытие. Здесь тот же порядок и
        // те же разделители; пустой перевод даёт пустую строку, как и в PHP.
        //
        // Зачем: «задача → нужный сервер» — смысловой вопрос. На запрос
        // «отправить письмо» лексический поиск находил набор иконок с иконкой
        // конверта; вектор находит именно почтовый сервер.
        'nj676_mcphub' => [
            'title'      => 'Каталог MCP-серверов (nj676)',
            'collection' => 'nj676_mcphub',
            'entity'     => 'server',
            'sql'        => "SELECT s.slug AS id,
                                    coalesce(s.name, '') || E'\\n' || coalesce(s.description, '') || E'\\n'
                                    || coalesce(s.name_ru, '') || E'\\n' || coalesce(s.description_ru, '') || E'\\n'
                                    || coalesce((SELECT string_agg(c.value, ' ')
                                                   FROM jsonb_array_elements_text(
                                                        CASE WHEN jsonb_typeof(s.categories) = 'array'
                                                             THEN s.categories ELSE '[]'::jsonb END
                                                   ) AS c(value)), '')
                                    || E'\\n'
                                    || coalesce((SELECT string_agg(
                                                        trim(coalesce(t.value->>'name', '') || ' '
                                                             || coalesce(t.value->>'description', '')), ' '
                                                        ORDER BY t.ord)
                                                   FROM jsonb_array_elements(
                                                        CASE WHEN jsonb_typeof(s.tools) = 'array'
                                                             THEN s.tools ELSE '[]'::jsonb END
                                                   ) WITH ORDINALITY AS t(value, ord)), '')
                                        AS content,
                                    jsonb_build_object('slug', s.slug, 'name', s.name) AS metadata
                             FROM nj_676_servers s
                             WHERE s.is_published = TRUE",
        ],
    ],

    /**
     * Поиск.
     *
     * max_distance — порог косинусной дистанции (0 — «то же самое», 1 — «ничего
     * общего»). Результаты дальше порога отбрасываются: без порога поиск
     * «находил» что угодно. NULL — не фильтровать.
     *
     * hybrid — если в пределах порога ничего не нашлось, добавить совпадения по
     * тексту (ILIKE): «вектор не уверен — покажем хотя бы буквальное совпадение».
     */
    'search' => [
        'max_distance' => 0.6,
        'hybrid'       => TRUE,
        'fulltext_min_length' => 3,   // короче — по тексту не ищем (слишком много шума)
    ],

    /**
     * Кэш эмбеддингов поисковых запросов (таблица nj_115_query_cache).
     *
     * Один и тот же запрос («вакансии аналитик», «резюме Python») не должен
     * каждый раз стоить вызова эмбеддинг-сервера. Кэш живёт в базе, поэтому
     * работает для всех процессов сайта и переживает перезапуск.
     */
    'cache' => [
        'enabled'   => TRUE,
        'ttl_days'  => 30,   // старше — удаляем
        'max_rows'  => 500,  // больше — чистим самые давно неиспользованные
    ],

    /**
     * Журнал поисковых запросов (таблица nj_115_searches).
     *
     * Панель /nj115 отвечает на вопрос «поиск реально находит?» — для этого
     * храним последние запросы: что искали, сколько нашлось (и чем — смыслом
     * или словами), сколько занял вызов и была ли ошибка.
     *
     * keep — сколько последних записей держим; 0 — журнал выключен.
     */
    'searches' => [
        'keep' => 200,
    ],
];
