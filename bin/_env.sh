#!/usr/bin/env bash
# =============================================================================
# Общая часть bash-обёрток: загрузка .env и поиск PHP.
#
# Подключается строкой `source "$(dirname "$0")/_env.sh"` и даёт две функции:
#   prx_load_env [файл]   — загрузить .env, НЕ затирая внешнее окружение;
#   prx_php_bin           — вывести подходящий интерпретатор PHP.
#
# Почему это отдельный файл, а не четыре копии
# --------------------------------------------
# bin/test, bin/console, bin/serve и bin/check-fresh.sh делали одно и то же
# двумя копипастами каждая — и обе с дефектами.
#
# 1. `set -a; source .env; set +a` затирал переменные, заданные вызывающим.
#    bin/check-fresh.sh экспортирует DB_DEFAULT_NAME=<временная БД> и запускает
#    bin/test — тот перечитывал .env, возвращал боевое имя базы, и тесты шли
#    против ОСНОВНОЙ базы. В CI 28.09.2026 это выглядело так: 89 миграций
#    применились, а сразу за ними четыре теста сообщили «таблица миграций не
#    найдена — выполните make migrate». Показательно, что в bin/console над
#    этим кодом уже стоял комментарий «не перезаписываем уже заданные
#    переменные»: намерение было записано, реализация ему не соответствовала.
#
#    Правило здесь то же, что и в PHP-загрузчике application/env.php:
#    **окружение главнее файла**. Файл заполняет только то, чего в окружении
#    ещё нет.
#
# 2. Поиск PHP (`for c in php8.4 php8.3 php php84`) был скопирован четыре раза
#    и в каждой копии мог разойтись.
#
# Совместимость: только конструкции bash 3.2 (штатный bash в macOS) —
# ассоциативных массивов здесь нет намеренно.
# =============================================================================

# Загрузить .env, не трогая уже заданные извне переменные.
prx_load_env() {
    local file="${1:-.env}"

    [[ -f "$file" ]] || return 0

    # Запоминаем внешние значения ТЕХ ключей, что встречаются в файле, —
    # чтобы вернуть их после source. Остальное окружение не трогаем.
    local line key restore=''

    while IFS= read -r line || [[ -n "$line" ]]; do
        key="${line%%=*}"
        key="${key#"${key%%[![:space:]]*}"}"   # пробелы слева
        key="${key%%[[:space:]]*}"             # всё после первого пробела

        [[ "$key" =~ ^[A-Za-z_][A-Za-z0-9_]*$ ]] || continue
        [[ -n "${!key+задано}" ]] || continue

        restore+="export $key=$(printf '%q' "${!key}")"$'\n'
    done < "$file"

    set -a
    # shellcheck disable=SC1090
    source "$file"
    set +a

    [[ -n "$restore" ]] && eval "$restore"

    return 0
}

# Вывести интерпретатор PHP: сначала $PHP_BIN, затем самый новый доступный.
prx_php_bin() {
    if [[ -n "${PHP_BIN:-}" ]]; then
        printf '%s' "$PHP_BIN"

        return 0
    fi

    local candidate

    for candidate in php8.4 php8.3 php php84; do
        if command -v "$candidate" >/dev/null 2>&1; then
            printf '%s' "$candidate"

            return 0
        fi
    done

    return 1
}
